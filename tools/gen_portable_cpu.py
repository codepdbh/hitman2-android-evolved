#!/usr/bin/env python3
"""
gen_portable_cpu.py - derive a pointer-width-independent cpu.h from PCRecomp's.

PCRecomp's runtime/recomp32_cpu/cpu.h states its assumption in its own header:
"The recomp runs as a 32-bit program so register values are real 32-bit host
pointers". Every memory helper therefore does `*(T *)(uintptr_t)a`. On ARM64
(and on the x86-64 test host) a guest address is not a host pointer.

Rather than fork the file, this rewrites exactly that one idiom:

        (uintptr_t)a      ->      GUEST_HOST(a)

where GUEST_HOST comes from runtime/guest_mem.h (guest base + address inside a
4 GiB reservation). The transformation is checked, not hoped for: after it,
no `uintptr_t` may remain in the header, and the number of rewrites must be
the number of occurrences found. If upstream changes shape, this fails loudly
instead of producing a header that half-works.

It also selects the simulated-TIB `fs:` path unconditionally (clang targeting
windows-msvc defines _MSC_VER, and the real-segment path is x86-32 only).

    python tools/gen_portable_cpu.py   ->   build/generated/include/cpu.h
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "pcrecomp" / "runtime" / "recomp32_cpu" / "cpu.h"
DST = ROOT / "build" / "generated" / "include" / "cpu.h"

IDIOM = re.compile(r"\(uintptr_t\)\s*a\b")


def generate(src: Path = SRC, dst: Path = DST) -> Path:
    text = src.read_text(encoding="utf-8")
    total = len(re.findall(r"\buintptr_t\b", text))
    out, n = IDIOM.subn("GUEST_HOST(a)", text)
    left = len(re.findall(r"\buintptr_t\b", out))
    if n == 0 or left != 0 or n != total:
        raise SystemExit(f"cpu.h changed shape upstream: {total} uintptr_t uses, {n} rewritten, {left} left. "
                         "Review tools/gen_portable_cpu.py before building.")
    marker = "#include <string.h>\n"
    if marker not in out:
        raise SystemExit("cpu.h: include anchor not found")
    out = out.replace(marker, marker + '#include "guest_mem.h"   /* GUEST_HOST: guest address -> host address */\n', 1)

    # The x87 control word is CPU state (recomp/h2_lifter.py explains why).
    field_anchor = "    uint32_t fs_base;\n} CPU;"
    if out.count(field_anchor) != 1:
        raise SystemExit("cpu.h: CPU struct tail not found exactly once")
    out = out.replace(field_anchor, "    uint32_t fs_base;\n"
                      "    uint32_t fpu_cw;    /* H2: x87 control word; rounding control is honoured */\n"
                      "    uint32_t df;        /* H2: direction flag (std/cld), honoured by string ops */\n} CPU;", 1)

    # Optional observation points on the x87 stack. They expand to nothing
    # unless a test harness defines them (tests/difftest uses them to notice a
    # function reading FPU inputs the test vector never supplied).
    hooks = {
        "static inline void   fpush(CPU *c, double v) { ":
            "static inline void   fpush(CPU *c, double v) { H2_FPU_ON_PUSH(c); ",
        "static inline double fpop(CPU *c) { ":
            "static inline double fpop(CPU *c) { H2_FPU_ON_POP(c); ",
        "static inline double *fst(CPU *c, int i) { ":
            "static inline double *fst(CPU *c, int i) { H2_FPU_ON_ST(c, i); ",
    }
    for old, new in hooks.items():
        if out.count(old) != 1:
            raise SystemExit(f"cpu.h: x87 helper not found exactly once: {old.strip()}")
        out = out.replace(old, new, 1)
    hook_defaults = ("#ifndef H2_FPU_ON_PUSH\n#define H2_FPU_ON_PUSH(c)  ((void)0)\n"
                     "#define H2_FPU_ON_POP(c)   ((void)0)\n#define H2_FPU_ON_ST(c, i) ((void)0)\n#endif\n")
    x87_anchor = "/* ---- x87 FPU ---- */"
    if out.count(x87_anchor) != 1:
        raise SystemExit("cpu.h: x87 section anchor not found exactly once")
    out = out.replace(x87_anchor, x87_anchor + "\n" + hook_defaults, 1)
    tail_anchor = "#endif /* PCRECOMP_CPU_H */"
    if out.count(tail_anchor) != 1:
        raise SystemExit("cpu.h: closing include guard not found exactly once")
    out = out.replace(tail_anchor, '#include "h2_x87.h"       /* project x87 helpers (runtime/) */\n\n' + tail_anchor, 1)
    banner = (
        "/* GENERATED by tools/gen_portable_cpu.py - do not edit, do not commit.\n"
        f" * Source: third_party/pcrecomp/runtime/recomp32_cpu/cpu.h (sha256 {hashlib.sha256(text.encode()).hexdigest()[:16]})\n"
        f" * {n} guest memory accesses rewritten from (uintptr_t)a to GUEST_HOST(a). */\n"
        "#ifndef RECOMP_FS_SIMULATED\n#define RECOMP_FS_SIMULATED 1\n#endif\n"
    )
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(banner + out, encoding="utf-8", newline="\n")
    return dst


if __name__ == "__main__":
    p = generate()
    print(p)
